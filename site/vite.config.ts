import { execFileSync } from 'node:child_process';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { defineConfig } from 'vite';

/**
 * The docs site: plain HTML pages + a few Lit elements, built from the repo.
 *   npm run docs:dev     (http://localhost:5180)
 *   npm run docs:build   → site/dist (relative URLs: serve it from any path, e.g. GitHub Pages /modx-ui/)
 *   npm run docs:preview
 * Before Vite starts: the Custom Elements Manifest is generated into src/generated/ (the API tables read it), and
 * one page per element (mx-*.html) is written from it, so a new component gets its page and tables without edits.
 */
const site = dirname(fileURLToPath(import.meta.url));
const repo = join(site, '..');

execFileSync(process.execPath, [join(repo, 'scripts/manifest.mjs'), join(site, 'src/generated/custom-elements.json')], { stdio: 'inherit' });
const manifest = JSON.parse(readFileSync(join(site, 'src/generated/custom-elements.json'), 'utf8')) as {
  modules: { declarations?: { tagName?: string; summary?: string }[] }[];
};
const tags = manifest.modules.flatMap((m) => (m.declarations ?? []).map((d) => d.tagName).filter((t): t is string => !!t)).sort();
const stub = (tag: string) => `<!doctype html>
<html lang="en" data-theme="auto">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>&lt;${tag}&gt; · modx-ui</title>
    <!-- generated by site/vite.config.ts from custom-elements.json: edit site/src/demos.ts or the component's JSDoc -->
    <script type="module" src="./src/main.ts"></script>
  </head>
  <body>
    <doc-shell page="${tag}"><doc-component tag="${tag}"></doc-component></doc-shell>
  </body>
</html>
`;
for (const tag of tags) writeFileSync(join(site, `${tag}.html`), stub(tag));

const pages = readdirSync(site).filter((f) => f.endsWith('.html'));

/* Inter and Space Grotesk: the families the tokens name (--mx-font-sans, --mx-font-display). */
const FONTS = '<link rel="preconnect" href="https://fonts.googleapis.com" /><link rel="preconnect" href="https://fonts.gstatic.com" crossorigin />'
  + '<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Inter:wght@300..700&family=Space+Grotesk:wght@400..700&display=swap" />'
  + '<meta name="color-scheme" content="dark light" /><link rel="icon" href="data:image/svg+xml,%3Csvg xmlns=%22http://www.w3.org/2000/svg%22 viewBox=%220 0 16 16%22%3E%3Cpath d=%22m8 1.75 5.5 3.1v6.3L8 14.25l-5.5-3.1v-6.3z%22 fill=%22%234743ff%22/%3E%3C/svg%3E" />';

export default defineConfig({
  root: site,
  plugins: [{ name: 'docs-head', transformIndexHtml: (page) => page.replace('</head>', `${FONTS}\n  </head>`) }],
  base: './',
  server: { port: 5180 },
  preview: { port: 5181 },
  build: {
    outDir: 'dist',
    emptyOutDir: true,
    rollupOptions: { input: Object.fromEntries(pages.map((p) => [p.replace(/\.html$/, ''), join(site, p)])) },
  },
});
